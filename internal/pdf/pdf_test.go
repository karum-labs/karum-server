package pdf

import (
	"bytes"
	"strings"
	"testing"
)

func TestRunSheetSeparatesFactsAndInferences(t *testing.T) {
	raw, err := RunSheet(Document{
		Brand:   "Ilegal Mezcal",
		City:    "Austin",
		Mode:    "wholesale",
		Formula: "S_door = 0.50 A_taste + 0.30 O_shelf + 0.20 D_demo",
		Stops: []Stop{{
			Rank: 1,
			Name: "Whisler's",
			Scores: []Fact{
				{Label: "Cultural affinity", Value: "91 raw", Source: "qloo_fact"},
				{Label: "Shelf opportunity", Value: "75", Source: "model_inference"},
			},
			SKU:   "Espadin",
			Pitch: "Walk in with the espadin.",
			Cites: []string{"ev-0001"},
		}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(raw, []byte("%PDF")) {
		t.Fatal("output is not a PDF")
	}
	text := extractVisible(raw)
	for _, want := range []string{"Qloo fact", "Model inference", "Whisler's", "ev-0001", "Espadin"} {
		if !strings.Contains(text, want) {
			t.Fatalf("pdf text missing %q\n%s", want, text)
		}
	}
}

func TestSiteBriefNamesCorridors(t *testing.T) {
	raw, err := SiteBrief(Document{
		Brand: "Muji",
		City:  "Brooklyn",
		Mode:  "flagship",
		Corridors: []Corridor{{
			Name:    "Williamsburg",
			Anchors: []string{"Choplet", "Kettl"},
			Demo:    "alignment 0.62",
		}},
	})
	if err != nil {
		t.Fatal(err)
	}
	text := extractVisible(raw)
	if !strings.Contains(text, "Williamsburg") || !strings.Contains(text, "Choplet") {
		t.Fatalf("brief text = %s", text)
	}
	if !strings.Contains(text, "Model inference") || !strings.Contains(text, "Qloo fact") {
		t.Fatalf("brief does not separate provenance: %s", text)
	}
}

func TestPitchExportRendersAllSections(t *testing.T) {
	raw, err := PitchExport(PitchDocument{
		Brand:          "Ilegal Mezcal",
		City:           "Austin",
		DoorName:       "Whisler's",
		Rank:           1,
		Opening:        "Good morning.",
		WhyThisDoor:    "Whisler's ranks first of 25.",
		Pitch:          "Take the Espadin Joven on a six-bottle trial.",
		ProductToLead:  "Espadin Joven",
		Ask:            "Will you stock it?",
		Close:          "Thanks for your time.",
		Score:          "72%",
		ScoreSource:    "model_inference",
		Sources: []Fact{
			{Label: "Whisler's ranks first of 25", Value: "ev-0001", Source: "qloo_fact"},
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(raw, []byte("%PDF")) {
		t.Fatal("output is not a PDF")
	}
	text := extractVisible(raw)
	for _, want := range []string{
		"Ilegal Mezcal", "Whisler's", "Good morning.", "Will you stock it?",
		"Thanks for your time.", "72%", "Sources", "ev-0001",
		"Generated by Karum",
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("pitch PDF text missing %q\n%s", want, text)
		}
	}
	// Evidence IDs live in the sources list, not in the prose sections.
	if !strings.Contains(text, "Whisler's ranks first of 25") {
		t.Fatalf("why_this_door section missing: %s", text)
	}
}

func extractVisible(raw []byte) string {
	var b strings.Builder
	for _, r := range string(raw) {
		if r >= 32 && r < 127 {
			b.WriteRune(r)
		} else {
			b.WriteByte(' ')
		}
	}
	return b.String()
}
