// Package pdf renders the field run-sheet, the flagship site brief, and a
// single-door pitch export.
//
// Qloo facts and model inferences are drawn in distinct styles, matching the
// provenance split in the proto comments. A render error is returned to the
// caller; the on-screen campaign is left untouched.
package pdf

import (
	"bytes"
	"embed"
	"fmt"

	"github.com/go-pdf/fpdf"
)

//go:embed assets/*
var assets embed.FS

// Brand palette (mirrors karum-client/lib/src/theme/brand_tokens.dart).
const (
	brandR, brandG, brandB = 0x0F, 0x4C, 0x4A // ink-teal #0F4C4A
	paperR, paperG, paperB = 0xF4, 0xF5, 0xF1 // paper #F4F5F1
	inkR, inkG, inkB       = 0x16, 0x21, 0x1F // ink #16211F
	muteR, muteG, muteB    = 0x56, 0x60, 0x5D // mute #56605D
)

// Fact is one line whose provenance the PDF must show.
type Fact struct {
	Label  string
	Value  string
	Source string // "qloo_fact", "google_fact", or "model_inference"
}

// Stop is one ordered door on the run-sheet.
type Stop struct {
	Rank   int
	Name   string
	Scores []Fact
	SKU    string
	Pitch  string
	Cites  []string
}

// Corridor is one flagship corridor.
type Corridor struct {
	Name    string
	Anchors []string
	Demo    string
}

// Document is the campaign slice either renderer needs.
type Document struct {
	Title     string
	City      string
	Brand     string
	Mode      string
	Formula   string
	Stops     []Stop
	Corridors []Corridor
}

// PitchDocument is a single door's pitch for export (PLAN.md §66).
type PitchDocument struct {
	Title         string
	Brand         string
	City          string
	DoorName      string
	Rank          int
	Opening       string
	WhyThisDoor   string
	Pitch         string
	ProductToLead string
	Ask           string
	Close         string
	Sources       []Fact
	Score         string
	ScoreSource   string
}

// RunSheet renders the wholesale or collab field sheet.
func RunSheet(doc Document) ([]byte, error) {
	return render(doc, false)
}

// SiteBrief renders the flagship corridor brief.
func SiteBrief(doc Document) ([]byte, error) {
	return render(doc, true)
}

// PitchExport renders a one-page pitch for one door (PLAN.md §66).
func PitchExport(doc PitchDocument) ([]byte, error) {
	pdf := newBranded("P", doc.Title)
	pdf.SetTitle(doc.Title, false)
	pdf.AddPage()
	writeHeader(pdf, "Door pitch", doc.Brand, doc.City, "")
	if doc.Score != "" {
		pdf.Ln(2)
		writeLine(pdf, Fact{Label: "Door score", Value: doc.Score, Source: doc.ScoreSource})
	}
	pdf.Ln(2)
	pdf.SetFont("Helvetica", "B", 13)
	setBrandText(pdf)
	pdf.CellFormat(0, 8, sanitize(fmt.Sprintf("%s — %s", doc.Brand, doc.DoorName)), "", 1, "L", false, 0, "")
	resetText(pdf)
	writeLine(pdf, Fact{Label: "Door", Value: doc.DoorName, Source: "qloo_fact"})
	if doc.Opening != "" {
		writeLine(pdf, Fact{Label: "Opening", Value: doc.Opening, Source: "model_inference"})
	}
	if doc.WhyThisDoor != "" {
		writeLine(pdf, Fact{Label: "Why this door", Value: doc.WhyThisDoor, Source: "model_inference"})
	}
	if doc.Pitch != "" {
		writeLine(pdf, Fact{Label: "Pitch", Value: doc.Pitch, Source: "model_inference"})
	}
	if doc.ProductToLead != "" {
		writeLine(pdf, Fact{Label: "Product to lead", Value: doc.ProductToLead, Source: "model_inference"})
	}
	if doc.Ask != "" {
		writeLine(pdf, Fact{Label: "Ask", Value: doc.Ask, Source: "model_inference"})
	}
	if doc.Close != "" {
		writeLine(pdf, Fact{Label: "Close", Value: doc.Close, Source: "model_inference"})
	}
	if len(doc.Sources) > 0 {
		pdf.Ln(2)
		pdf.SetFont("Helvetica", "B", 13)
		setBrandText(pdf)
		pdf.CellFormat(0, 8, "Sources", "", 1, "L", false, 0, "")
		resetText(pdf)
		for _, source := range doc.Sources {
			writeLine(pdf, source)
		}
	}
	pdf.Ln(4)
	setMuteText(pdf)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.CellFormat(0, 5, sanitize("Generated by Karum; figures cite Qloo and Google Places. Every number in the prose traces to a cited evidence id."), "", 1, "L", false, 0, "")
	resetText(pdf)
	if err := pdf.Error(); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func render(doc Document, brief bool) ([]byte, error) {
	pdf := newBranded("P", doc.Title)
	pdf.SetTitle(doc.Title, false)
	pdf.AddPage()
	title := doc.Title
	if title == "" {
		if brief {
			title = "Site-selection brief"
		} else {
			title = "Field run-sheet"
		}
	}
	writeHeader(pdf, title, doc.Brand, doc.City, doc.Mode)
	if doc.Formula != "" {
		pdf.Ln(2)
		writeLine(pdf, Fact{Label: "Door score", Value: doc.Formula, Source: "model_inference"})
	}
	pdf.Ln(2)
	writeLegend(pdf)
	if brief {
		if len(doc.Corridors) == 0 {
			pdf.MultiCell(0, 5, "No corridors were returned for this run.", "", "L", false)
		}
		for _, corridor := range doc.Corridors {
			pdf.Ln(2)
			pdf.SetFont("Helvetica", "B", 13)
			setBrandText(pdf)
			pdf.CellFormat(0, 8, sanitize(corridor.Name), "", 1, "L", false, 0, "")
			resetText(pdf)
			writeLine(pdf, Fact{Label: "Corridor", Value: corridor.Name, Source: "qloo_fact"})
			if len(corridor.Anchors) > 0 {
				writeLine(pdf, Fact{Label: "Anchor neighbours", Value: join(corridor.Anchors), Source: "qloo_fact"})
			}
			if corridor.Demo != "" {
				writeLine(pdf, Fact{Label: "Demographic line", Value: corridor.Demo, Source: "model_inference"})
			}
		}
	} else {
		for _, stop := range doc.Stops {
			pdf.Ln(2)
			pdf.SetFont("Helvetica", "B", 13)
			setBrandText(pdf)
			pdf.CellFormat(0, 8, sanitize(fmt.Sprintf("%d. %s", stop.Rank, stop.Name)), "", 1, "L", false, 0, "")
			resetText(pdf)
			writeLine(pdf, Fact{Label: "Door", Value: stop.Name, Source: "qloo_fact"})
			for _, score := range stop.Scores {
				writeLine(pdf, score)
			}
			if stop.SKU != "" {
				writeLine(pdf, Fact{Label: "SKU", Value: stop.SKU, Source: "model_inference"})
			}
			if stop.Pitch != "" {
				writeLine(pdf, Fact{Label: "Pitch", Value: stop.Pitch, Source: "model_inference"})
			}
			if len(stop.Cites) > 0 {
				writeLine(pdf, Fact{Label: "Citations", Value: join(stop.Cites), Source: "qloo_fact"})
			}
		}
	}
	if err := pdf.Error(); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func newBranded(orientation, title string) *fpdf.Fpdf {
	pdf := fpdf.New(orientation, "mm", "A4", "")
	pdf.SetCompression(false)
	pdf.SetTitle(title, false)
	fontData, err := assets.ReadFile("assets/bricolage-bold.ttf")
	if err == nil {
		pdf.AddUTF8FontFromBytes("Bricolage", "B", fontData)
	}
	monoData, err := assets.ReadFile("assets/plexmono-medium.ttf")
	if err == nil {
		pdf.AddUTF8FontFromBytes("IBMPlexMono", "", monoData)
	}
	logoData, err := assets.ReadFile("assets/logo.png")
	if err == nil {
		pdf.RegisterImageOptionsReader("karum-logo", fpdf.ImageOptions{ImageType: "PNG"}, bytes.NewReader(logoData))
	}
	pdf.SetFooterFunc(func() {
		pdf.SetY(-12)
		setMuteText(pdf)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.CellFormat(0, 5, sanitize("Karum . figures cite Qloo & Google Places"), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 5, fmt.Sprintf("Page %d", pdf.PageNo()), "", 0, "R", false, 0, "")
	})
	return pdf
}

func writeHeader(pdf *fpdf.Fpdf, title, brand, city, mode string) {
	pdf.SetFillColor(brandR, brandG, brandB)
	pdf.Rect(0, 0, 210, 18, "F")
	if info := pdf.GetImageInfo("karum-logo"); info != nil {
		pdf.Image("karum-logo", 8, 3, 12, 12, false, "PNG", 0, "")
	}
	pdf.SetXY(24, 4)
	pdf.SetTextColor(paperR, paperG, paperB)
	pdf.SetFont("Bricolage", "B", 14)
	pdf.CellFormat(0, 6, "KARUM", "", 1, "L", false, 0, "")
	pdf.SetXY(24, 10)
	pdf.SetFont("Helvetica", "", 9)
	sub := title
	if brand != "" {
		sub = fmt.Sprintf("%s  .  %s", brand, title)
	}
	if city != "" {
		sub = fmt.Sprintf("%s  .  %s", sub, city)
	}
	pdf.CellFormat(0, 6, sanitize(sub), "", 1, "L", false, 0, "")
	resetText(pdf)
	pdf.SetY(22)
}

func writeLegend(pdf *fpdf.Fpdf) {
	pdf.SetFont("Helvetica", "", 9)
	pdf.CellFormat(0, 5, "Qloo fact  -  roman type", "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "I", 9)
	pdf.CellFormat(0, 5, "Model inference  -  italic type", "", 1, "L", false, 0, "")
}

func writeLine(pdf *fpdf.Fpdf, fact Fact) {
	style := ""
	prefix := "Qloo fact"
	switch fact.Source {
	case "model_inference":
		style = "I"
		prefix = "Model inference"
	case "google_fact":
		prefix = "Google fact"
	}
	pdf.SetFont("Helvetica", style, 10)
	pdf.MultiCell(0, 5, sanitize(prefix+": "+fact.Label+" - "+fact.Value), "", "L", false)
}

func join(items []string) string {
	out := ""
	for i, item := range items {
		if i > 0 {
			out += ", "
		}
		out += item
	}
	return out
}

func sanitize(s string) string {
	var b bytes.Buffer
	for _, r := range s {
		switch {
		case r == '\n' || r == '\r' || r == '\t':
			b.WriteByte(' ')
		case r < 32 || r > 126:
			b.WriteByte(' ')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func setBrandText(pdf *fpdf.Fpdf) {
	pdf.SetTextColor(brandR, brandG, brandB)
}

func resetText(pdf *fpdf.Fpdf) {
	pdf.SetTextColor(inkR, inkG, inkB)
}

func setMuteText(pdf *fpdf.Fpdf) {
	pdf.SetTextColor(muteR, muteG, muteB)
}